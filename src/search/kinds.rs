/// The built-in `kinds.generated_markers`.
pub const DEFAULT_MARKERS: [&str; 4] = [
    "@generated",
    "DO NOT EDIT",
    "Code generated by",
    "auto-generated",
];

/// The built-in `kinds.generated_marker_lines`.
pub const DEFAULT_MARKER_LINES: usize = 5;

/// At most this many bytes are read to find the markers.
const MAX_MARKER_BYTES: u64 = 64 * 1024;

/// The configuration of the kinds (CONFIG.md#kinds); the built-in rules by default.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KindOptions {
    /// A file with one of them in its first lines is generated.
    pub generated_markers: Vec<String>,
    /// How many first lines are checked for the markers.
    pub generated_marker_lines: usize,
    /// Wildcards of the paths of each kind.
    pub generated: Vec<String>,
    pub test: Vec<String>,
    pub doc: Vec<String>,
    pub config: Vec<String>,
}

impl Default for KindOptions {
    fn default() -> Self {
        let list = |items: &[&str]| items.iter().map(ToString::to_string).collect();
        Self {
            generated_markers: list(&DEFAULT_MARKERS),
            generated_marker_lines: DEFAULT_MARKER_LINES,
            generated: list(&DEFAULT_GENERATED),
            test: list(&DEFAULT_TEST),
            doc: list(&DEFAULT_DOC),
            config: list(&DEFAULT_CONFIG),
        }
    }
}

/// The rules of the kinds.
#[derive(Debug, Clone)]
pub struct KindRules {
    generated: Vec<Regex>,
    test: Vec<Regex>,
    doc: Vec<Regex>,
    config: Vec<Regex>,
    markers: Vec<String>,
    marker_lines: usize,
}

fn compile(patterns: &[String], case_insensitive: bool) -> Vec<Regex> {
    patterns
        .iter()
        .map(|p| {
            wildcard::compile(&crate::query::nfc(p), case_insensitive)
                .expect("the wildcards of the kinds are checked with their keys")
        })
        .collect()
}

impl KindRules {
    /// The rules of the options; wildcards are matched with the given case sensitivity.
    pub fn new(options: &KindOptions, case_insensitive: bool) -> Self {
        Self {
            generated: compile(&options.generated, case_insensitive),
            test: compile(&options.test, case_insensitive),
            doc: compile(&options.doc, case_insensitive),
            config: compile(&options.config, case_insensitive),
            markers: options.generated_markers.clone(),
            marker_lines: options.generated_marker_lines,
        }
    }

    /// The built-in rules.
    #[cfg(test)]
    pub fn builtin(case_insensitive: bool) -> Self {
        Self::new(&KindOptions::default(), case_insensitive)
    }

    /// The kind of an entry with the `/`-separated relative path `rel`; the markers are read from `file` only for
    /// regular files; `source` is whether the language of the entry is code.
    pub fn classify(&self, rel: &str, file: &Path, is_file: bool, source: bool) -> Kind {
        let any = |rules: &[Regex]| rules.iter().any(|r| r.is_match(rel));
        if any(&self.generated) || (is_file && self.has_marker(file)) {
            Kind::Generated
        } else if any(&self.test) {
            Kind::Test
        } else if any(&self.doc) {
            Kind::Doc
        } else if any(&self.config) {
            Kind::Config
        } else if source {
            Kind::Source
        } else {
            Kind::Other
        }
    }

    /// Whether a path is generated by the wildcards, without the markers.
    pub fn is_generated_path(&self, rel: &str) -> bool {
        self.generated.iter().any(|p| p.is_match(rel))
    }

    /// Whether a regular file is generated.
    pub fn is_generated(&self, rel: &str, file: &Path) -> bool {
        self.generated.iter().any(|p| p.is_match(rel)) || self.has_marker(file)
    }

    fn has_marker(&self, file: &Path) -> bool {
        if self.markers.is_empty() {
            return false;
        }
        let Ok(f) = File::open(file) else {
            return false;
        };
        let mut reader = BufReader::new(f.take(MAX_MARKER_BYTES));
        let mut line = Vec::new();
        for _ in 0..self.marker_lines {
            line.clear();
            match reader.read_until(b'\n', &mut line) {
                Ok(0) | Err(_) => return false,
                Ok(_) => {
                    let text = String::from_utf8_lossy(&line);
                    if self.markers.iter().any(|m| text.contains(m.as_str())) {
                        return true;
                    }
                }
            }
        }
        false
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const MISSING: &str = "/nonexistent/file";

    fn kind(rel: &str, source: bool) -> Kind {
        KindRules::builtin(false).classify(rel, Path::new(MISSING), true, source)
    }

    #[test]
    fn by_path() {
        assert_eq!(kind("Cargo.lock", false), Kind::Generated);
        assert_eq!(kind("web/dist/app.min.js", true), Kind::Generated);
        assert_eq!(kind("src/schema.generated.rs", true), Kind::Generated);
        assert_eq!(kind("tests/a.rs", true), Kind::Test);
        assert_eq!(kind("pkg/main_test.go", true), Kind::Test);
        assert_eq!(kind("notes_test.md", false), Kind::Test);
        assert_eq!(kind("README.md", false), Kind::Doc);
        assert_eq!(kind("docs/x.rs", true), Kind::Doc);
        assert_eq!(kind("Cargo.toml", false), Kind::Config);
        assert_eq!(kind(".github/workflows/ci.yml", false), Kind::Config);
        assert_eq!(kind("src/main.rs", true), Kind::Source);
        assert_eq!(kind("data.csv", false), Kind::Other);
    }

    #[test]
    fn other_markers_and_none() {
        let tmp = tempfile::tempdir().unwrap();
        let file = tmp.path().join("b.rs");
        std::fs::write(&file, "// AUTOGEN\nfn b() {}\n").unwrap();
        let options = |markers: &[&str]| KindOptions {
            generated_markers: markers.iter().map(ToString::to_string).collect(),
            ..KindOptions::default()
        };
        assert!(KindRules::new(&options(&["AUTOGEN"]), false).is_generated("b.rs", &file));
        assert!(!KindRules::new(&options(&["autogen"]), false).is_generated("b.rs", &file));
        assert!(!KindRules::new(&options(&[]), false).is_generated("b.rs", &file));
        assert!(!KindRules::builtin(false).is_generated("b.rs", &file));
    }

    #[test]
    fn by_marker_in_the_first_lines() {
        let tmp = tempfile::tempdir().unwrap();
        let rules = KindRules::builtin(false);
        let first = tmp.path().join("a.rs");
        std::fs::write(&first, "// @generated\nfn a() {}\n").unwrap();
        assert!(rules.is_generated("a.rs", &first));
        assert_eq!(rules.classify("a.rs", &first, true, true), Kind::Generated);
        assert_eq!(rules.classify("a.rs", &first, false, true), Kind::Source);
        let fifth = tmp.path().join("b.go");
        std::fs::write(&fifth, "1\n2\n3\n4\n// Code generated by x. DO NOT EDIT.\n").unwrap();
        assert!(rules.is_generated("b.go", &fifth));
        let sixth = tmp.path().join("c.rs");
        std::fs::write(&sixth, "1\n2\n3\n4\n5\n// @generated\n").unwrap();
        assert!(!rules.is_generated("c.rs", &sixth));
    }
}
